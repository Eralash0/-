_PHRASES_SORTED = sorted(RU_PHRASES.items(), key=lambda kv: len(kv[0]), reverse=True)

_TEXT_NODE = re.compile(r">(\s*)([^<>]+?)(\s*)<")


def _plural(n, one, few, many):
    n10, n100 = n % 10, n % 100
    if n10 == 1 and n100 != 11:
        return one
    if 2 <= n10 <= 4 and not 12 <= n100 <= 14:
        return few
    return many


def translate_html(html: str) -> str:
    # 1) толық мәтін түйіндері
    def node(m):
        key = " ".join(m.group(2).split())
        ru = RU_EXACT.get(key)
        if ru is None:
            return m.group(0)
        return ">" + m.group(1) + ru + m.group(3) + "<"

    html = _TEXT_NODE.sub(node, html)

    # 2) атрибуттар мен айнымалысы бар мәтіндер
    for kz, ru in _PHRASES_SORTED:
        html = html.replace(kz, ru)

    # 3) сан + сөз (септік жалғауымен)
    html = re.sub(
        r"(\d+) сұрақ(?!\w)",
        lambda m: f"{m.group(1)} " + _plural(int(m.group(1)), "вопрос", "вопроса", "вопросов"),
        html,
    )
    html = re.sub(
        r"(\d+) тест(?!\w)",
        lambda m: f"{m.group(1)} " + _plural(int(m.group(1)), "тест", "теста", "тестов"),
        html,
    )
    html = re.sub(
        r"(\d+) балл(?!\w)",
        lambda m: f"{m.group(1)} " + _plural(int(m.group(1)), "балл", "балла", "баллов"),
        html,
    )
    html = re.sub(r"Қате (\d+)", r"Ошибка \1", html)
    return html